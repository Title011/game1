/* ทุกด่านตรวจลำดับเดียวกัน: ของครบไหม → เป็นวงจรปิดไหม → ผ่าน
   จึงเขียนเป็นข้อกำหนดสั้น ๆ แล้วให้ตัวสร้างประกอบ check ให้

     need   ['รหัสอุปกรณ์','ข้อความเมื่อยังไม่มี']  ต้องมีอย่างน้อย 1 ชิ้น
            เขียนเป็นรหัสเปล่า ๆ ได้ = ใช้ข้อความ 'ยังขาด: <ชื่ออุปกรณ์>'
     count  ['รหัสอุปกรณ์',จำนวน,'ข้อความเมื่อยังไม่ครบ']  %n = จำนวนที่วางอยู่จริง
     win    ข้อความตอนผ่านด่าน

   ตรวจ need ให้ครบก่อน แล้วจึงตรวจ count ตามลำดับที่เขียนไว้ */
function levelCheck(spec){
  return function(items,wires){
    var ids=items.map(function(i){return i.deviceId;});
    var need=spec.need||[], count=spec.count||[];
    for(var i=0;i<need.length;i++){
      var bare=(typeof need[i]==='string');
      var id=bare?need[i]:need[i][0];
      if(ids.indexOf(id)<0){
        return {ok:false,msg:bare?('ยังขาด: '+DEVICES[id].name):need[i][1]};
      }
    }
    for(var j=0;j<count.length;j++){
      var have=0;
      for(var k=0;k<ids.length;k++) if(ids[k]===count[j][0]) have++;
      if(have<count[j][1]) return {ok:false,msg:count[j][2].replace('%n',have)};
    }
    var c=isClosedCircuit(items,wires); if(!c.ok) return c;
    return {ok:true,msg:spec.win};
  };
}

